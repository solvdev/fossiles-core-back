    @Test
    void revertDeletesOnlyRowsOfThatBatchAndCannotBeRepeated() throws Exception {
        Long first = service.commit(request(false, augustData(), SHA_A)).getBatches().get(0).getBatchId();
        // datos de otro mes/lote que no deben tocarse
        KioskExcelDataDto sep = KioskExcelDataDto.builder().days(List.of(KioskExcelDataDto.Day.builder()
                        .date(LocalDate.of(2025, 9, 2)).values(values("MIRAFLORES", "50")).build()))
                .goals(new LinkedHashMap<>()).rates(new LinkedHashMap<>()).costs(new LinkedHashMap<>())
                .blockedCells(new ArrayList<>()).build();
        KioskExcelCommitRequest sepReq = request(false, sep, SHA_B);
        sepReq.getFiles().get(0).setMonth(9);
        Long second = service.commit(sepReq).getBatches().get(0).getBatchId();
        // edición manual posterior de la config de agosto: debe respetarse al revertir
        jdbc.update("UPDATE kiosk_period_config SET source = 'MANUAL' WHERE site_id = 1 AND month = 8");

        KioskExcelBatchSummaryResponse reverted = service.revert(first);
        assertThat(reverted.getStatus()).isEqualTo("REVERTED");
        assertThat(reverted.getRevertedBy()).isEqualTo(42L);
        assertThat(reverted.getRevertedAt()).isNotNull();
        assertThat(count("SELECT COUNT(*) FROM kiosk_daily_sales_hist WHERE import_batch_id = ?", first)).isZero();
        assertThat(count("SELECT COUNT(*) FROM kiosk_fixed_cost WHERE import_batch_id = ?", first)).isZero();
        assertThat(count("SELECT COUNT(*) FROM kiosk_period_config WHERE site_id = 1 AND month = 8")).isEqualTo(1);
        assertThat(count("SELECT COUNT(*) FROM kiosk_daily_sales_hist WHERE import_batch_id = ?", second)).isEqualTo(1);

        assertThatThrownBy(() -> service.revert(first)).isInstanceOf(BusinessException.class)
                .hasMessageContaining("ya fue revertido");
        assertThatThrownBy(() -> service.revert(9999L)).hasMessageContaining("no encontrado");
    }

