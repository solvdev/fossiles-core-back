    @Test
    void commitWritesSalesConfigAndCostsTaggedWithTheBatch() throws Exception {
        KioskExcelCommitResponse res = service.commit(request(false, augustData(), SHA_A));

        assertThat(res.getBatches()).hasSize(1);
        KioskExcelCommitResponse.BatchResult b = res.getBatches().get(0);
        assertThat(b.getSalesRows()).isEqualTo(3);   // null = sin fila; 0 = fila
        assertThat(b.getConfigRows()).isEqualTo(1);  // PERI sólo trae meta 0 => sin config
        assertThat(b.getCostRows()).isEqualTo(1);    // LUZ null no se escribe
        assertThat(b.getReplacedRows()).isZero();
        assertThat(b.getWarnings()).anyMatch(w -> w.startsWith("MISSING_GOAL"));

        assertThat(count("SELECT COUNT(*) FROM kiosk_daily_sales_hist WHERE import_batch_id = ?", b.getBatchId())).isEqualTo(3);
        assertThat(jdbc.queryForObject("SELECT amount FROM kiosk_daily_sales_hist WHERE site_id = 1 AND sale_date = DATE '2025-08-02'",
                BigDecimal.class)).isEqualByComparingTo("100.50");
        assertThat(jdbc.queryForObject("SELECT amount FROM kiosk_daily_sales_hist WHERE site_id = 2 AND sale_date = DATE '2025-08-02'",
                BigDecimal.class)).isEqualByComparingTo("0");
        assertThat(count("SELECT COUNT(*) FROM kiosk_daily_sales_hist WHERE sale_date = DATE '2025-08-01'")).isZero();
        Map<String, Object> cfg = jdbc.queryForMap("SELECT * FROM kiosk_period_config WHERE site_id = 1 AND year = 2025 AND month = 8");
        assertThat(cfg.get("SOURCE")).isEqualTo("EXCEL");
        assertThat((BigDecimal) cfg.get("SALES_GOAL")).isEqualByComparingTo("130000");
        assertThat((BigDecimal) cfg.get("CARD_COMMISSION_PCT")).isEqualByComparingTo("0.025");
        assertThat(((Number) cfg.get("IMPORT_BATCH_ID")).longValue()).isEqualTo(b.getBatchId());
        assertThat(((Number) cfg.get("UPDATED_BY")).longValue()).isEqualTo(42L);
        assertThat(count("SELECT COUNT(*) FROM kiosk_fixed_cost WHERE import_batch_id = ? AND category_code = 'ALQUILER'", b.getBatchId())).isEqualTo(1);

        Map<String, Object> batch = jdbc.queryForMap("SELECT * FROM kiosk_import_batch WHERE id = ?", b.getBatchId());
        assertThat(batch.get("STATUS")).isEqualTo("APPLIED");
        assertThat(((Number) batch.get("SALES_ROWS")).intValue()).isEqualTo(3);
        assertThat(((Number) batch.get("CREATED_BY")).longValue()).isEqualTo(42L);
        assertThat(service.list()).hasSize(1);
        assertThat(service.list().get(0).getWarnings()).isNotEmpty();
    }

    @Test
    void commitCreatesHistoricalSiteAndAliasForNewColumns() throws Exception {
        KioskExcelDataDto data = augustData();
        data.getDays().get(1).getValues().put("SANTA AMELIA", new BigDecimal("77.25"));
        KioskExcelCommitRequest req = request(false, data, SHA_A);
        req.getFiles().get(0).getSiteMapping().put("SANTA AMELIA", KioskExcelCommitRequest.SiteMappingEntry.builder()
                .create(KioskExcelCommitRequest.CreateSite.builder().name("SANTA AMELIA").status("CLOSED")
                        .closedOn(LocalDate.of(2025, 8, 31)).build()).build());
        // mapeo manual de una columna con otro nombre al sitio existente 2 => alias nuevo
        data.getDays().get(1).getValues().put("PERI NORTE", new BigDecimal("3"));
        req.getFiles().get(0).getSiteMapping().put("PERI NORTE", KioskExcelCommitRequest.SiteMappingEntry.builder().siteId(2L).build());
        // ...pero PERI ya apunta al sitio 2: debe rechazarse por duplicado
        assertThatThrownBy(() -> service.commit(req)).isInstanceOf(BusinessException.class).hasMessageContaining("mismo sitio");

        data.getDays().get(1).getValues().remove("PERI NORTE");
        req.getFiles().get(0).getSiteMapping().remove("PERI NORTE");
        service.commit(req);

        Map<String, Object> site = jdbc.queryForMap("SELECT * FROM kiosk_site WHERE name = 'SANTA AMELIA'");
        assertThat(site.get("LOCATION_ID")).isNull();
        assertThat(site.get("STATUS")).isEqualTo("CLOSED");
        assertThat(site.get("CLOSED_ON").toString()).isEqualTo("2025-08-31");
        long id = ((Number) site.get("ID")).longValue();
        assertThat(count("SELECT COUNT(*) FROM kiosk_site_alias WHERE alias_normalized = 'SANTA AMELIA' AND site_id = ?", id)).isEqualTo(1);
        assertThat(count("SELECT COUNT(*) FROM kiosk_daily_sales_hist WHERE site_id = ?", id)).isEqualTo(1);
    }

