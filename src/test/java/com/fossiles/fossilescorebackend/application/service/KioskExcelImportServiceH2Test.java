    @Test
    void previewMatchesAliasesFlagsUnmatchedAndRoundTripsIntoCommit() throws Exception {
        byte[] xlsx = KioskExcelTestFixtures.februaryWorkbook("150..5", false, null);

        KioskExcelPreviewResponse preview = service.previewBytes(List.of(
                new KioskExcelImportService.NamedBytes("VENTAS FEBRERO 2025.xlsx", xlsx)));
        KioskExcelPreviewResponse.FilePreview file = preview.getFiles().get(0);
        assertThat(file.getYear()).isEqualTo(2025);
        assertThat(file.getMonth()).isEqualTo(2);
        assertThat(file.getSha256()).hasSize(64);
        assertThat(file.getAlreadyImported()).isNull();
        assertThat(file.getColumns()).extracting(KioskExcelPreviewResponse.ColumnMapping::getMatchStatus)
                .containsExactly("MATCHED", "MATCHED", "UNMATCHED");
        assertThat(file.getColumns().get(0).getMatchedSiteId()).isEqualTo(1L);
        assertThat(file.getColumns().get(0).getNormalized()).isEqualTo("MIRAFLORES");
        List<KioskExcelIssueDto> blocking = file.getIssues().stream().filter(i -> "BLOCKING".equals(i.getSeverity())).toList();
        assertThat(blocking).extracting(KioskExcelIssueDto::getCode)
                .containsExactlyInAnyOrder("NON_NUMERIC_CELL", "UNMATCHED_COLUMN");
        assertThat(file.getIssues()).extracting(KioskExcelIssueDto::getId).doesNotHaveDuplicates();
        assertThat(file.getStats().getColumns()).isEqualTo(3);
        assertThat(file.getStats().getDays()).isEqualTo(28);

        // preview -> JSON -> commit (como lo hace el front)
        String json = mapper.writeValueAsString(file.getData());
        KioskExcelDataDto data = mapper.readValue(json, KioskExcelDataDto.class);
        String issueId = blocking.stream().filter(i -> "NON_NUMERIC_CELL".equals(i.getCode())).findFirst().orElseThrow().getId();
        String commitJson = "{\"replaceExisting\":false,\"files\":[{\"fileName\":\"VENTAS FEBRERO 2025.xlsx\",\"sha256\":\""
                + file.getSha256() + "\",\"year\":2025,\"month\":2,"
                + "\"siteMapping\":{\"NUEVO KIOSCO\":{\"create\":{\"name\":\"NUEVO KIOSCO\"}}},"
                + "\"resolutions\":{\"" + issueId + "\":150.5},\"data\":" + mapper.writeValueAsString(data) + "}]}";
        KioskExcelCommitRequest request = mapper.readValue(commitJson, KioskExcelCommitRequest.class);

        KioskExcelCommitResponse res = service.commit(request);
        KioskExcelCommitResponse.BatchResult b = res.getBatches().get(0);
        assertThat(b.getSalesRows()).isEqualTo(27 * 3);
        assertThat(b.getConfigRows()).isEqualTo(3 - 0);   // NUEVO KIOSCO: meta 0 pero con tasas
        assertThat(b.getCostRows()).isEqualTo(10 + 10 + 8);
        assertThat(jdbc.queryForObject("SELECT amount FROM kiosk_daily_sales_hist WHERE site_id = 2 AND sale_date = DATE '2025-02-10'",
                BigDecimal.class)).isEqualByComparingTo("150.5");
        assertThat(count("SELECT COUNT(*) FROM kiosk_site WHERE name = 'NUEVO KIOSCO' AND location_id IS NULL")).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT sales_goal FROM kiosk_period_config WHERE site_id = 3", BigDecimal.class)).isNull();

        // segunda vista previa: ya importado (mismo archivo) + DUPLICATE_FILE; sitio nuevo ya tiene alias
        KioskExcelPreviewResponse.FilePreview again = service.previewBytes(List.of(
                new KioskExcelImportService.NamedBytes("VENTAS FEBRERO 2025.xlsx", xlsx))).getFiles().get(0);
        assertThat(again.getAlreadyImported()).isNotNull();
        assertThat(again.getAlreadyImported().getBatchId()).isEqualTo(b.getBatchId());
        assertThat(again.getAlreadyImported().isSameFile()).isTrue();
        assertThat(again.getIssues()).extracting(KioskExcelIssueDto::getCode).contains("DUPLICATE_FILE");
        assertThat(again.getColumns()).extracting(KioskExcelPreviewResponse.ColumnMapping::getMatchStatus)
                .containsOnly("MATCHED");

        // tras revertir ya no figura como importado
        service.revert(b.getBatchId());
        KioskExcelPreviewResponse.FilePreview third = service.previewBytes(List.of(
                new KioskExcelImportService.NamedBytes("VENTAS FEBRERO 2025.xlsx", xlsx))).getFiles().get(0);
        assertThat(third.getAlreadyImported()).isNull();
    }

    @Test
    void previewMarksTwoColumnsOfTheSameSiteAsAmbiguousAndBrokenFilesAsFileError() throws Exception {
        jdbc.update("INSERT INTO kiosk_site_alias (alias_normalized, site_id) VALUES ('NUEVO KIOSCO', 1)");
        byte[] xlsx = KioskExcelTestFixtures.februaryWorkbook(null, false, null);
        KioskExcelPreviewResponse preview = service.previewBytes(List.of(
                new KioskExcelImportService.NamedBytes("VENTAS FEBRERO 2025.xlsx", xlsx),
                new KioskExcelImportService.NamedBytes("VENTAS FEBRERO 2025 copia.xlsx", xlsx),
                new KioskExcelImportService.NamedBytes("~$VENTAS.xlsx", new byte[]{1, 2, 3})));
        KioskExcelPreviewResponse.FilePreview first = preview.getFiles().get(0);
        assertThat(first.getColumns()).extracting(KioskExcelPreviewResponse.ColumnMapping::getMatchStatus)
                .containsExactly("AMBIGUOUS", "MATCHED", "AMBIGUOUS");
        // mismo archivo repetido en la carga
        assertThat(preview.getFiles().get(1).getIssues()).extracting(KioskExcelIssueDto::getCode).contains("DUPLICATE_FILE");
        KioskExcelPreviewResponse.FilePreview broken = preview.getFiles().get(2);
        assertThat(broken.getData()).isNull();
        assertThat(broken.getIssues()).extracting(KioskExcelIssueDto::getCode).containsExactly("FILE_ERROR");
        assertThat(broken.getIssues().get(0).getSeverity()).isEqualTo("BLOCKING");
    }

