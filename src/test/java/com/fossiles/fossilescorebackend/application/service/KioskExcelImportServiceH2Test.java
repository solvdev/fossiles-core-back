    @Test
    void existingDataRequiresReplaceAndIsThenReplaced() throws Exception {
        service.commit(request(false, augustData(), SHA_A));

        assertThatThrownBy(() -> service.commit(request(false, augustData(), SHA_B)))
                .isInstanceOf(BusinessException.class).hasMessageContaining("replaceExisting");

        KioskExcelDataDto changed = augustData();
        changed.getDays().get(1).getValues().put("MIRAFLORES", new BigDecimal("999.99"));
        changed.getDays().get(2).getValues().put("MIRAFLORES", null);
        changed.getCosts().get("MIRAFLORES").put("ALQUILER", new BigDecimal("1"));
        KioskExcelCommitResponse res = service.commit(request(true, changed, SHA_B));

        assertThat(res.getBatches().get(0).getReplacedRows()).isEqualTo(3 + 1 + 1);
        assertThat(count("SELECT COUNT(*) FROM kiosk_daily_sales_hist WHERE site_id = 1")).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT amount FROM kiosk_daily_sales_hist WHERE site_id = 1", BigDecimal.class))
                .isEqualByComparingTo("999.99");
        assertThat(jdbc.queryForObject("SELECT amount FROM kiosk_fixed_cost WHERE site_id = 1 AND category_code = 'ALQUILER'",
                BigDecimal.class)).isEqualByComparingTo("1");
        assertThat(count("SELECT COUNT(*) FROM kiosk_import_batch")).isEqualTo(2);
    }

